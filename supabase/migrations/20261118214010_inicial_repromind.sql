CREATE TABLE public.ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    categoria TEXT,
    prioridade TEXT DEFAULT 'Media',
    status TEXT DEFAULT 'Aberta',
    data_criacao TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    impacto INTEGER,
    frequencia INTEGER,
    usuarios_afetados INTEGER
);

CREATE TABLE public.relatorios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES public.ocorrencias(id),
    resumo TEXT,
    hipotese TEXT,
    evidencias TEXT,
    testes_sugeridos TEXT,
    data_criacao TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    modo TEXT,
    informacoes TEXT,
    hipoteses TEXT,
    confianca TEXT,
    status_investigacao TEXT,
    testes_priorizados TEXT
);

CREATE TABLE public.respostas_investigacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES public.ocorrencias(id) ON DELETE CASCADE,
    pergunta TEXT NOT NULL,
    resposta TEXT,
    ordem INTEGER NOT NULL,
    data_criacao TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario TEXT NOT NULL,
    senha_hash TEXT NOT NULL,
    senha_salt TEXT NOT NULL,
    papel TEXT NOT NULL DEFAULT 'membro' CHECK (papel IN ('admin', 'membro')),
    ativo SMALLINT NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
    deve_trocar_senha SMALLINT NOT NULL DEFAULT 0 CHECK (deve_trocar_senha IN (0, 1)),
    data_criacao TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX idx_usuarios_nome_usuario_lower
    ON public.usuarios (LOWER(nome_usuario));

CREATE TABLE public.sessoes (
    token_hash TEXT PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    expira_em BIGINT NOT NULL,
    data_criacao TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sessoes_expira_em
    ON public.sessoes (expira_em);

-- Persist login throttling so limits are shared between serverless instances.
CREATE TABLE public.tentativas_login (
    escopo TEXT NOT NULL CHECK (escopo IN ('credencial', 'ip')),
    chave_hash TEXT NOT NULL CHECK (char_length(chave_hash) = 64),
    inicio BIGINT NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
    PRIMARY KEY (escopo, chave_hash)
);

CREATE TABLE public.ia_usos_reais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    ocorrencia_id BIGINT NOT NULL REFERENCES public.ocorrencias(id) ON DELETE RESTRICT,
    fingerprint_entrada TEXT NOT NULL CHECK (char_length(fingerprint_entrada) = 64),
    status TEXT NOT NULL CHECK (status IN ('reservada', 'concluida', 'falhou', 'cancelada', 'expirada')),
    modelo TEXT,
    solicitada_em BIGINT NOT NULL,
    reservada_ate BIGINT,
    finalizada_em BIGINT,
    tokens_entrada INTEGER CHECK (tokens_entrada IS NULL OR tokens_entrada >= 0),
    tokens_saida INTEGER CHECK (tokens_saida IS NULL OR tokens_saida >= 0),
    codigo_erro TEXT CHECK (codigo_erro IS NULL OR char_length(codigo_erro) <= 100)
);

CREATE INDEX idx_ia_usos_reais_usuario_tempo
    ON public.ia_usos_reais (usuario_id, solicitada_em, status);

CREATE INDEX idx_ia_usos_reais_tempo_status
    ON public.ia_usos_reais (solicitada_em, status);

CREATE INDEX idx_ia_usos_reais_ocorrencia_tempo
    ON public.ia_usos_reais (ocorrencia_id, solicitada_em);

CREATE INDEX idx_ia_usos_reais_status_tempo
    ON public.ia_usos_reais (status, solicitada_em);

CREATE UNIQUE INDEX idx_ia_usos_reais_reserva_duplicada
    ON public.ia_usos_reais (ocorrencia_id, fingerprint_entrada)
    WHERE status = 'reservada';

